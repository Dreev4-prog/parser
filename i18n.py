from db import SessionLocal
from models import AppSetting

LANG_RU = "ru"
LANG_EN = "en"
SUPPORTED_LANGUAGES = {LANG_RU, LANG_EN}
LANGUAGE_KEY_PREFIX = "user_language:"

_language_cache: dict[int, str | None] = {}


def normalize_language(value: str | None) -> str | None:
    value = (value or "").strip().lower()
    if value in SUPPORTED_LANGUAGES:
        return value
    return None


async def get_user_language(user_id: int) -> str | None:
    user_id = int(user_id)
    if user_id in _language_cache:
        return _language_cache[user_id]
    async with SessionLocal() as session:
        row = await session.get(AppSetting, f"{LANGUAGE_KEY_PREFIX}{user_id}")
        lang = normalize_language(row.value if row else None)
    _language_cache[user_id] = lang
    return lang


async def set_user_language(user_id: int, language: str) -> str:
    user_id = int(user_id)
    lang = normalize_language(language)
    if lang is None:
        raise ValueError(f"Unsupported language: {language!r}")
    key = f"{LANGUAGE_KEY_PREFIX}{user_id}"
    async with SessionLocal() as session:
        row = await session.get(AppSetting, key)
        if row is None:
            row = AppSetting(key=key, value=lang, updated_at=datetime.utcnow())
            session.add(row)
        else:
            row.value = lang
            row.updated_at = datetime.utcnow()
        await session.commit()
    _language_cache[user_id] = lang
    return lang


def language_name(language: str | None) -> str:
    return "English" if normalize_language(language) == LANG_EN else "Русский"


