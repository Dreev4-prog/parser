_WORD_RE = re.compile(r"(?iu)\b(" + "|".join(re.escape(k) for k in sorted(WORD_MAP, key=len, reverse=True)) + r")\b")


def translate_text(text: str | None, language: str | None) -> str | None:
    if not text or normalize_language(language) != LANG_EN:
        return text
    out = str(text)
    for source, target in ALL_PHRASES:
        if source not in out:
            continue
        if re.fullmatch(r"[A-Za-zА-Яа-яЁё]+", source):
            out = re.sub(rf"(?<!\w){re.escape(source)}(?!\w)", lambda _m, t=target: t, out)
        else:
            out = out.replace(source, target)

    def word_repl(match: re.Match[str]) -> str:
        src = match.group(0)
        target = WORD_MAP.get(src.lower(), src)
        if src[:1].isupper() and target:
            return target[:1].upper() + target[1:]
        return target

    out = _WORD_RE.sub(word_repl, out)
    # Common dynamic units/plurals after the phrase pass.
    out = re.sub(r"(?<=\d)\s*стр\.?\b", " pages", out, flags=re.I)
    out = re.sub(r"(?<=\d)\s*сек\.?\b", " sec", out, flags=re.I)
    out = re.sub(r"(?<=\d)\s*мин\.?\b", " min", out, flags=re.I)
    out = re.sub(r"(?<=\d)\s*ч\b", "h", out, flags=re.I)
    return out
